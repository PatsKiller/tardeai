def test_http_flow_prompt_unlock_retry(listeners, server_mod):
    cfg, p = listeners(enabled=True)
    ident = {"Tailscale-User-Login": ALLOWED, **SAME_ORIGIN}
    st, raw = _req(p["serve_proxy"], "/api/v2/brokers/schwab/reauth-url", headers=ident)
    body = json.loads(raw)
    assert st == 403 and body["auth"] == "step_up" and body["step_up"] == {
        "available": True, "endpoint": cc_auth.STEP_UP_ENDPOINT}
    st, raw = _req(p["serve_proxy"], cc_auth.STEP_UP_STATUS_ENDPOINT + "?action=schwab_reauth", headers=ident)
    s = json.loads(raw)
    assert st == 200 and s["enabled"] and s["available_here"] and s["unlocked_until"] is None
    st, raw = _req(p["serve_proxy"], cc_auth.STEP_UP_ENDPOINT, method="POST", headers=ident,
                   body={"action": "schwab_reauth", "code": "000000" if cc_totp.totp(_key(cfg), _now()) != "000000" else "111111"})
    assert st == 401
    code = cc_totp.totp(_key(cfg), _now())
    st, raw = _req(p["serve_proxy"], cc_auth.STEP_UP_ENDPOINT, method="POST", headers=ident,
                   body={"action": "schwab_reauth", "code": code})
    assert st == 200 and json.loads(raw)["ok"] is True
    st, raw = _req(p["serve_proxy"], "/api/v2/brokers/schwab/reauth-url", headers=ident)
    assert st == 200 and json.loads(raw)["fake"] is True
    # service listener: still refused, and cannot verify a code at all
    st, _ = _req(p["service"], "/api/v2/brokers/schwab/reauth-url", headers={cfg.token_header: TOKEN})
    assert st == 403
    st, raw = _req(p["service"], cc_auth.STEP_UP_ENDPOINT, method="POST", headers={cfg.token_header: TOKEN},
                   body={"action": "schwab_reauth", "code": code})
    assert st == 403 and json.loads(raw)["error"] == cc_auth.STEP_UP_SERVICE_MESSAGE
    # cross-site code submission is refused by CSRF before the handler
    st, _ = _req(p["serve_proxy"], cc_auth.STEP_UP_ENDPOINT, method="POST",
                 headers={"Tailscale-User-Login": ALLOWED, "Origin": "https://evil.example", "Sec-Fetch-Site": "cross-site"},
                 body={"action": "schwab_reauth", "code": code})
    assert st == 403
    rows = [json.loads(line) for line in cfg.decision_log.read_text().splitlines()]
    kinds = {(r["kind"], r["outcome"]) for r in rows}
    assert ("step_up_verify", "unlocked") in kinds and ("step_up_verify", "fail") in kinds
    used = [r for r in rows if r["outcome"] == "allow_step_up"]
    assert len(used) == 1 and used[0]["step_up_action"] == "schwab_reauth" and used[0]["principal"] == PRINCIPAL
    assert code not in cfg.decision_log.read_text()
    assert [c for c in server_mod._fake_calls if c[1] == "/api/v2/brokers/schwab/reauth-url"] == [
        ("GET", "/api/v2/brokers/schwab/reauth-url")]


