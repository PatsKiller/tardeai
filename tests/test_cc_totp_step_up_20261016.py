def _raw_committed() -> dict:
    import yaml
    return yaml.safe_load((ROOT / "config" / "cc_auth.yaml").read_text(encoding="utf-8"))


def _write_secret(path: Path) -> str:
    secret = cc_totp.generate_secret()
    cc_totp.write_private_json(path, {"schema": cc_totp.SECRET_SCHEMA, "secret_b32": secret,
                                      "activated_at": "2026-10-16T00:00:00+00:00"})
    return secret


def _key(cfg) -> bytes:
    return cc_totp.decode_secret(json.loads(cfg.totp.secret_file.read_text())["secret_b32"])


def _mgr(cfg) -> cc_totp.StepUpManager:
    return cc_totp.StepUpManager(cfg.totp, clock=lambda: T0)


def _raw(tmp_path, *, enabled, actions=None, logins=None, report_only=False):
    raw = _raw_committed()
    sec = raw["cc_auth"]
    sec["report_only"] = report_only
    tok = tmp_path / "cc_service_token"
    tok.write_text(TOKEN + "\n", encoding="utf-8")
    os.chmod(tok, 0o600)
    sec["service_token"]["file"] = str(tok)
    sec["decision_log"] = str(tmp_path / "decisions.jsonl")
    if logins:
        sec["allowed_logins"] = logins
    t = sec["step_up"]["totp"]
    t["enabled"] = enabled
    t["secret_file"] = str(tmp_path / "cfg" / "cc_totp_secret.json")
    t["state_file"] = str(tmp_path / "state" / "cc_totp_state.json")
    if actions is not None:
        t["actions"] = actions
    return raw


def _write_cfg(tmp_path) -> Path:
    import yaml
    p = tmp_path / "cc_auth.yaml"
    p.write_text(yaml.safe_dump(_raw(tmp_path, enabled=False)), encoding="utf-8")
    return p


def _cfg(tmp_path, *, enabled, enroll=True, actions=None, logins=None, report_only=False):
    raw = _raw(tmp_path, enabled=enabled, actions=actions, logins=logins, report_only=report_only)
    cfg = cc_auth.config_from_mapping(raw, source="test", apply_env=False)
    if enroll:
        _write_secret(cfg.totp.secret_file)
    return cfg, cc_auth.ServiceTokenStore(cfg.token_file, cfg.token_min_length)


