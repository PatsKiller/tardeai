def test_unlock_bound_to_identity_and_action(tmp_path):
    cfg, store = _cfg(tmp_path, enabled=True, actions=["schwab_reauth", "credential_change"],
                      logins=[ALLOWED, "other@example.com"])
    mgr = cc_auth.step_up_manager(cfg)
    st, _ = cc_auth.handle_step_up(cfg, "serve_proxy", PRINCIPAL,
                                   {"action": "schwab_reauth", "code": cc_totp.totp(_key(cfg), _now())})
    assert st == 200
    reauth = "/api/v2/brokers/schwab/reauth-url"
    cred = "/api/v2/snaptrade/credentials"
