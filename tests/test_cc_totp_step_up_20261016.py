def test_enrollment_requires_tty_and_verified_code(tmp_path, monkeypatch):
    import cc_totp_enroll as enr
    cfg_path = _write_cfg(tmp_path)
    args = enr.argparse.Namespace(config=str(cfg_path), secret_file=None, state_file=None, account=None, no_qr=True)
    out: list[str] = []
    assert enr.enroll(args, prompt=lambda _: "", out=out.append, is_tty=False) == 2
    assert "operator-only" in out[-1]
    s = cc_auth.load_config(cfg_path).totp
    assert not s.secret_file.exists()

    pending = s.secret_file.with_name(s.secret_file.name + ".pending")

    def _prompt_wrong(_):
        return "000000"
    assert enr.enroll(args, prompt=_prompt_wrong, out=out.append, clock=lambda: T0, is_tty=True) in (0, 1)
    if s.secret_file.exists():  # 1-in-a-million: 000000 was the right code
        pytest.skip("random secret produced 000000")
    assert pending.exists() and not s.secret_file.exists()
    assert oct(os.stat(pending).st_mode & 0o777) == "0o600"
    assert enr.enroll(args, prompt=_prompt_wrong, out=out.append, is_tty=True) == 2  # unfinished pending
    pending.unlink()

    def _prompt_right(_):
        doc = json.loads(pending.read_text())  # the test's own throwaway secret
        return cc_totp.totp(cc_totp.decode_secret(doc["secret_b32"]), T0)
    assert enr.enroll(args, prompt=_prompt_right, out=out.append, clock=lambda: T0, is_tty=True) == 0
    assert s.secret_file.exists() and not pending.exists()
    assert oct(os.stat(s.secret_file).st_mode & 0o777) == "0o600"
    doc = json.loads(s.secret_file.read_text())
