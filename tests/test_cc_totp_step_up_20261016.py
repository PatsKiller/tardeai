    assert d.allowed and d.detail.get("step_up_used") == "schwab_reauth"
    # another tailnet login does not inherit the unlock
    d = cc_auth.evaluate_request(cfg, "serve_proxy", "GET", reauth, {"Tailscale-User-Login": "other@example.com"}, store)
    assert not d.allowed and d.reason == cc_auth.STEP_UP_CODE_MESSAGE
    # the same login, another action class: still refused
    d = cc_auth.evaluate_request(cfg, "serve_proxy", "POST", cred,
                                 {"Tailscale-User-Login": ALLOWED, **SAME_ORIGIN, "Content-Type": "application/json"}, store)
    assert not d.allowed and d.step_up_action == "credential_change"
    assert mgr.is_unlocked(PRINCIPAL, "schwab_reauth") and not mgr.is_unlocked(PRINCIPAL, "credential_change")


