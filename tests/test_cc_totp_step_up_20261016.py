def test_rate_limit_lockout_refuses_even_a_correct_code(tmp_path):
    cfg, _ = _cfg(tmp_path, enabled=True)
    rows: list[dict] = []
    clock = [T0]
    mgr = cc_totp.StepUpManager(cfg.totp, log=rows.append, clock=lambda: clock[0])
    good = cc_totp.totp(_key(cfg), T0)
    wrong = f"{(int(good) + 1) % 1_000_000:06d}"
    for i in range(4):
        st, out = mgr.verify(principal=PRINCIPAL, action="schwab_reauth", code=wrong)
        assert st == 401 and out["attempts_left"] == 4 - i
    st, out = mgr.verify(principal=PRINCIPAL, action="schwab_reauth", code=wrong)
    assert st == 429 and out["locked_until"] == T0 + 900
    st, out = mgr.verify(principal=PRINCIPAL, action="schwab_reauth", code=good)
    assert st == 429 and not mgr.is_unlocked(PRINCIPAL, "schwab_reauth")
    # lockout persists across a restart
    st, _ = cc_totp.StepUpManager(cfg.totp, clock=lambda: T0 + 10).verify(
        principal=PRINCIPAL, action="schwab_reauth", code=good)
    assert st == 429
    clock[0] = T0 + 901
    fresh = cc_totp.totp(_key(cfg), clock[0])
    st, _ = mgr.verify(principal=PRINCIPAL, action="schwab_reauth", code=fresh)
    assert st == 200
    outcomes = [r["outcome"] for r in rows]
    assert outcomes.count("fail") == 5 and "lockout_start" in outcomes and "lockout_active" in outcomes
    assert outcomes[-1] == "unlocked"
    blob = json.dumps(rows)
    assert good not in blob and wrong not in blob and fresh not in blob  # never log a code


