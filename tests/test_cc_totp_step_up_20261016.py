def test_window_is_plus_minus_one_step_only():
    now = T0
    for delta, ok in ((-60, False), (-30, True), (0, True), (30, True), (60, False)):
        code = cc_totp.totp(SEED20, now + delta)
        got = cc_totp.match_counter(SEED20, code, now, window=1)
        assert (got is not None) is ok, delta
    assert cc_totp.match_counter(SEED20, cc_totp.totp(SEED20, now - 30), now, window=0) is None


