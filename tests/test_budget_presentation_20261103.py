def test_source_reread_inside_transaction_refuses_a_racing_change(rig):
    calls = []

    def racing_source(scope, budget):
        calls.append((scope, budget))
        row = canonical()
        if len(calls) > 1:
            row["actual"] = 41
        return row

    rig.ctx.budget_snapshot = racing_source
    status, result = post(rig)
    assert status == 409, result
    assert calls == [(SCOPE, BUDGET), (SCOPE, BUDGET)]
    assert rig.ledger.rows() == []


def test_dry_run_changes_with_the_actual_observation(rig):
    first_status, first = post(rig, body(dry_run=True))
    assert first_status == 200, first
    rig.current["actual"] = 41
    get_status, observed = get(rig)
    assert get_status == 200, observed
    current_binding = observed["data"]["current"]["source_binding"]
    second_status, second = post(rig, body(dry_run=True, source_binding=current_binding))
    assert second_status == 200, second
    assert first["data"]["would_append"]["observed"]["actual"] == 40
    assert second["data"]["would_append"]["observed"]["actual"] == 41
    assert first["data"]["would_append"]["source_binding"] != second["data"]["would_append"]["source_binding"]
    assert not rig.ledger.path.exists()
    assert rig.current["limit"] == 30 and rig.current["breached"] is True


