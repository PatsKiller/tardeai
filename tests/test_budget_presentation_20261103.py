def test_append_is_attributed_idempotent_and_presentation_only(rig):
    before = json.dumps(rig.current, sort_keys=True, allow_nan=False)
    status, result = post(rig)
    assert status == 200, result
    row = result["data"]
    assert row["event"] == "BUDGET_PRESENTATION_DECISION" and row["subtype"] == SUBTYPE
    assert row["effect"] == "PRESENTATION_ONLY" and row["actor"] == ACTOR
    assert row["action"] == "intentional_until" and row["intentional_until"] == UNTIL
    assert row["source_binding"] == {"as_of": AS_OF, "sha256": GOLDEN}
    assert len(row["hash_self"]) == 64
    durable = rig.ledger.path.read_bytes()
    retry_status, retry = post(rig)
    assert retry_status == 200 and retry["data"]["hash_self"] == row["hash_self"]
    assert rig.ledger.path.read_bytes() == durable
    assert len(rig.ledger.rows()) == 1
    status, readback = get(rig)
    assert status == 200, readback
    item = readback["data"]["decisions"]["items"][0]
    assert item["scope_id"] == SCOPE and item["budget"] == BUDGET
    assert item["breached"] is True and item["active"] is True
    assert item["actor"] == ACTOR and item["receipt"] == row["hash_self"]
    assert item["intentional_until"] == UNTIL and len(item["history"]) == 1
    unchanged(rig, before)


