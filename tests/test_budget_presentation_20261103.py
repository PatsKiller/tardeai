@pytest.mark.parametrize("reason", ["expired", "source_changed"])
def test_readback_invalidates_intent_but_preserves_history_and_breach(rig, reason):
    assert post(rig)[0] == 200
    receipt = rig.ledger.rows()[0]["hash_self"]
    durable = rig.ledger.path.read_bytes()
    if reason == "expired":
        rig.clock[0] = NOW + timedelta(hours=2)
    else:
        rig.current["actual"] = 41
    result = rig.core.budget_presentation_decisions(rig.ledger.rows(), [copy.deepcopy(rig.current)], rig.clock[0])
    item = result["items"][0]
    assert item["active"] is False and item["breached"] is True
    assert len(item["history"]) == 1 and len(result["history"]) == 1
    assert item["history"][0]["hash_self"] == receipt
    assert rig.ledger.path.read_bytes() == durable
    assert rig.current["limit"] == 30 and rig.current["breached"] is True


