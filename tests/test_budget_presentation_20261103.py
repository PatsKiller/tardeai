def body(**updates):
    # Fixed independent golden, never the production binding result.
    return {
        "subtype": SUBTYPE,
        "action": "intentional_until",
        "scope_id": SCOPE,
        "budget": BUDGET,
        "source_binding": {"as_of": AS_OF, "sha256": GOLDEN},
        "intentional_until": UNTIL,
        "request_id": "synthetic_request_001",
        "comment": "Synthetic presentation acknowledgement.",
        **updates,
    }


def post(rig, payload=None):
    return rig.api.handle(
        rig.api.PREFIX + "/budget-presentation/decide", "POST", body() if payload is None else payload, ctx=rig.ctx
    )


def get(rig):
    return rig.api.handle(
        rig.api.PREFIX + "/budget-presentation", "GET", query={"scope_id": SCOPE, "budget": BUDGET}, ctx=rig.ctx
    )


def unchanged(rig, before):
    assert json.dumps(rig.current, sort_keys=True, allow_nan=False) == before
    assert rig.current["breached"] is True
    assert rig.current["actual"] == 40 and rig.current["limit"] == 30


def test_binding_matches_independent_scoped_contract_golden(modules):
    core, _ = modules
    assert core.budget_presentation_binding(canonical()) == {"as_of": AS_OF, "sha256": GOLDEN}
    equivalent = canonical()
    equivalent["actual"], equivalent["limit"] = 40.0, 30.0
    equivalent["source_binding"]["as_of"] = "2032-04-12T14:00:00+00:00"
    assert core.budget_presentation_binding(equivalent) == {"as_of": AS_OF, "sha256": GOLDEN}


