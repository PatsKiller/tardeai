#!/usr/bin/env python3
"""Generate the INACTIVE Ask hourly/material native workflow and its integrity manifest.

The two native Schedule Triggers request only their own server-minted /due slots.
The existing Run Lane subworkflow owns signed dispatch, result polling and retries;
n8n never chooses a model, writes the Ask ledger, or sends a notification itself.
This generator writes source artifacts only. It does not import or activate n8n.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
for _p in (str(ROOT), str(ROOT / "scripts")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

import n8n_workflow_templates as T  # noqa: E402

NO_CONSUMER_REASON = "Source generator consumed by its --check and the workflow framework's fresh-render gate."
GENERATOR = "scripts/build_cio_ask_lifecycle_workflow.py"
REL = Path("docs/ops/packets/ask-hourly-20261026/n8n")
OUT = ROOT / REL
WID = "tradeai-cio-ask-lifecycle-native"
FILE = "workflow.native.candidate.json"
HOURLY = "cio-ask-lifecycle"
MATERIAL = "cio-ask-material-events"
LANES = (HOURLY, MATERIAL)
SCHEDULES = ((HOURLY, "0 0 * * * *"), (MATERIAL, "0 */5 * * * *"))
RUNBOOK_ID = "cio-ask-lifecycle-native"
MAX_ATTEMPTS = 1  # /due owns retry eligibility; never invent another slot or attempt.
OUTCOME_TIMEOUT_S = 600 + T.PROCESS_OUTCOME_MARGIN_S
EXECUTION_TIMEOUT_S = T.run_lane_worst_case_s(MAX_ATTEMPTS, OUTCOME_TIMEOUT_S) + 120

N_HOURLY, N_MATERIAL, N_MANUAL = "Schedule hourly ET", "Schedule material ET", "Manual hourly check"
N_HCTX, N_MCTX, N_RELAY, N_LANE = "Hourly context", "Material context", "Relay", "Route lane"
N_HDUE, N_MDUE, N_VALIDATE = "GET hourly due", "GET material due", "Validate due"
N_RUN, N_RECORD, N_ROUTE = "Run lane", "Record run", "Route outcome"
N_OK, N_DATA, N_FAIL = "Outcome success", "Outcome as data", "Fail run"


def framework_meta() -> dict:
    return {
        "schema": "N8nWorkflowFrameworkMeta@v1",
        # This graph orchestrates host lanes through Run Lane; it contains no direct /llm_step node.
        "class": "business-critical",
        "owner": "cio",
        "stage": "shadow",
        "lanes": list(LANES),
        "connects_to": [
            "relay:GET /due (authenticated, exact lane filter; server-minted schedule key)",
            f"workflow:{T.RUN_LANE_ID} (waits; relay:POST /run and GET /run_outcome only through Run Lane)",
            f"workflow:{T.FABRIC_ERROR_ID} (errorWorkflow; relay:POST /intent, host communications gateway)",
            *[f"lane:{lane} (config/n8n_run_allowlist.json; live_arg null until reviewed admission)" for lane in LANES],
            "store:data/cio/cio_ask_events.jsonl (host-owned Ask writer and exact consumer readback)",
            "receipt:data/runtime/cio-ask-lifecycle_last.json and cio-ask-material-events_last.json; immutable v2 attempts",
            "consumer:scripts/lib/cio_ask_lifecycle_health.py (per-thread evidence, memory_sync, readback, delivery)",
        ],
        "runbook_id": RUNBOOK_ID,
        "runbook_path": str(REL / "README.txt"),
        "health_contract_id": HOURLY,
        "rollback": "Follow docs/ops/packets/ask-hourly-20261026/n8n/README.txt: unpublish this workflow and set both "
        "registry dispatch modes off; keep the host ledger and existing receipt evidence. Native lanes have no cron twin.",
        "native_recovery": {
            "schema": "N8nNativeRecovery@v1",
            "mode": "manual_stop_then_reviewed_canary",
            "workflow_id": WID,
            "lanes": list(LANES),
            "runbook_id": RUNBOOK_ID,
            "runbook_path": str(REL / "README.txt"),
            "stop_actions": ["unpublish_workflow", "disable_lane_dispatch"],
            "retry_owner": T.RUN_LANE_ID,
            "max_attempts": MAX_ATTEMPTS,
            "dead_letter": "host_ledger",
            "cron_fallback": False,
        },
        "llm_steps": [],  # The host executor binds the registered whole-panel process set.
    }


def _context_js(lane: str) -> str:
    return f"// Generated by {GENERATOR}; no caller-minted slot.\nreturn [{{ json: {{ lane_id: {json.dumps(lane)} }} }}];\n"


def _due_js() -> str:
    return "\n".join(
        [
            f"// Generated by {GENERATOR}; the relay, not this workflow, chooses slot and mode.",
            f"const lane = $('{N_RELAY}').first().json.lane_id;",
            f"if (!{json.dumps(LANES)}.includes(lane)) throw new Error('due: unknown lane');",
            "const r = $input.first().json || {};",
            "if (r.statusCode !== 200 || r.error) throw new Error('due: relay unavailable or refused');",
            "const due = r.body;",
            f"if (!due || due.schema !== {json.dumps(T.DUE_SCHEMA)} || due.ok !== true || due.source !== 'schedule') {{",
            "  throw new Error('due: invalid response');",
            "}",
            "if (!Array.isArray(due.items) || due.items.length > 1) throw new Error('due: invalid item count');",
            "return due.items.map(it => {",
            "  if (!it || it.lane_id !== lane || !['dry_run', 'live'].includes(it.mode)) throw new Error('due: wrong lane/mode');",
            "  const prefix = 'd:' + lane + ':' + it.mode + ':';",
            "  const key = it.idempotency_key;",
            "  if (typeof key !== 'string' || !key.startsWith(prefix) || !/^[0-9]{8}T[0-9]{4}(:a[2-9])?$/.test(key.slice(prefix.length))) {",
            "    throw new Error('due: not a bound server schedule key');",
            "  }",
            "  return { json: { lane_id: lane, mode: it.mode, idempotency_key: key,",
            f"    max_attempts: {MAX_ATTEMPTS}, outcome_timeout_s: {OUTCOME_TIMEOUT_S}, process_id: {json.dumps(WID)} }} }};",
            "});",
            "",
        ]
    )


def _record_js() -> str:
    return "\n".join(
        [
            f"// Generated by {GENERATOR}; save the host join identity, never fabricate success.",
            f"const c = $('{N_VALIDATE}').first().json;",
            "const r = $input.first().json || {};",
            "$execution.customData.set('run_id', String(r.run_id || c.idempotency_key));",
            "$execution.customData.set('lane_id', String(c.lane_id));",
            f"$execution.customData.set('process_id', {json.dumps(WID)});",
            "if (r.schema !== 'RunLaneResult@v1' || r.lane_id !== c.lane_id || r.mode !== c.mode || r.run_id !== c.idempotency_key) {",
            "  throw new Error('run-lane: result identity/schema mismatch');",
            "}",
            "return [{ json: r }];",
            "",
        ]
    )


def _outcome_js() -> str:
    return "\n".join(
        [
            "// Forward the actual Run Lane status. Receipt + canonical per-thread evidence decides business health.",
            "const r = $input.first().json || {};",
            "return [{ json: { ...r, business_health: 'CioAskLifecycleHealth@v1',",
            "  business_freshness_proven: false } }];",
            "",
        ]
    )


def build() -> dict:
    nodes: list[dict] = []
    for name, context, lane, expression, y in (
        (N_HOURLY, N_HCTX, HOURLY, SCHEDULES[0][1], 0),
        (N_MATERIAL, N_MCTX, MATERIAL, SCHEDULES[1][1], 240),
    ):
        nodes.append(
            {
                "id": T._f_node_id(WID, name),
                "name": name,
                "type": "n8n-nodes-base.scheduleTrigger",
                "typeVersion": 1.2,
                "position": [0, y],
                "parameters": {"rule": {"interval": [{"field": "cronExpression", "expression": expression}]}},
            }
        )
        nodes.append(T._f_code(WID, context, _context_js(lane), [240, y]))
    nodes += [
        {
            "id": T._f_node_id(WID, N_MANUAL),
            "name": N_MANUAL,
            "type": "n8n-nodes-base.manualTrigger",
            "typeVersion": 1,
            "position": [0, -240],
            "parameters": {},
        },
        T._f_set_relay(WID, N_RELAY, [480, 120]),
        T._f_switch(WID, N_LANE, "={{ $json.lane_id }}", LANES, [720, 120]),
        T._f_http(
            WID, N_HDUE, method="GET", path_expr=f"/due?source=schedule&lane={HOURLY}&limit=1", position=[960, 0]
        ),
        T._f_http(
            WID, N_MDUE, method="GET", path_expr=f"/due?source=schedule&lane={MATERIAL}&limit=1", position=[960, 240]
        ),
        T._f_code(WID, N_VALIDATE, _due_js(), [1200, 120]),
        T._p_run(WID, N_RUN, [1440, 120]),
        T._f_code(WID, N_RECORD, _record_js(), [1680, 120]),
        T._f_switch(WID, N_ROUTE, "={{ $json.status }}", T.RUN_LANE_TERMINAL, [1920, 120]),
        T._f_code(WID, N_OK, _outcome_js(), [2160, 0]),
        T._f_code(WID, N_DATA, _outcome_js(), [2160, 160]),
        T._f_code(
            WID,
            N_FAIL,
            "const r = $input.first().json || {};\nthrow new Error('Ask lifecycle: ' + String(r.status || 'invalid_route') + ' ' + String(r.reason || '').slice(0, 80));\n",
            [2160, 320],
        ),
    ]
    conns: dict = {}
    for source, dest in (
        (N_HOURLY, N_HCTX),
        (N_MATERIAL, N_MCTX),
        (N_MANUAL, N_HCTX),
        (N_HCTX, N_RELAY),
        (N_MCTX, N_RELAY),
        (N_RELAY, N_LANE),
        (N_HDUE, N_VALIDATE),
        (N_MDUE, N_VALIDATE),
        (N_VALIDATE, N_RUN),
        (N_RUN, N_RECORD),
        (N_RECORD, N_ROUTE),
    ):
        T._p_conn(conns, source, [[(dest, 0)]])
    T._p_conn(conns, N_LANE, [[(N_HDUE, 0)], [(N_MDUE, 0)], [(N_FAIL, 0)]])
    by_status = {"success": N_OK, "failed": N_FAIL, "refused_policy": N_DATA, "skipped_lock": N_DATA}
    T._p_conn(conns, N_ROUTE, [[(by_status[s], 0)] for s in T.RUN_LANE_TERMINAL] + [[(N_FAIL, 0)]])
    wf = {
        "id": WID,
        "name": WID,
        "active": False,
        "nodes": sorted(nodes, key=lambda n: n["name"]),
        "connections": conns,
        "settings": T._fabric_settings(WID, EXECUTION_TIMEOUT_S),
        "meta": {
            "generator": GENERATOR,
            "kind": "native-business",
            "design": "DSN-20261026-ask-hourly-P1-T4",
            "activation": "INACTIVE source candidate; reviewed admission and trusted host/runtime evidence required",
            "framework": framework_meta(),
        },
    }
    wf["meta"]["graph_sha256"] = T.graph_hash(wf)
    wf["meta"]["policy_sha256"] = T.policy_hash()
    return wf


def problems(wf: dict) -> list[str]:
    """Fabric invariants plus this workflow's narrower read-only discovery/run boundary."""
    bad = T.validate_fabric_workflow(wf, {WID, T.RUN_LANE_ID, T.FABRIC_ERROR_ID})
    for node in wf.get("nodes") or []:
        p = node.get("parameters") or {}
        if node.get("type") == "n8n-nodes-base.httpRequest":
            if p.get("method") != "GET" or p.get("url") not in {
                "={{ $('Relay').first().json.TRADEAI_N8N_RUN_URL }}" + f"/due?source=schedule&lane={lane}&limit=1"
                for lane in LANES
            }:
                bad.append(f"native_discovery_route:{node.get('name')}")
        elif node.get("type") == "n8n-nodes-base.executeWorkflow":
            if (p.get("workflowId") or {}).get("value") != T.RUN_LANE_ID or not (p.get("options") or {}).get(
                "waitForSubWorkflow"
            ):
                bad.append(f"native_call_not_run_lane:{node.get('name')}")
        elif node.get("type") in {
            "n8n-nodes-base.webhook",
            "n8n-nodes-base.executeWorkflowTrigger",
            "n8n-nodes-base.errorTrigger",
        }:
            bad.append(f"native_trigger_refused:{node.get('name')}")
    return bad


def render() -> dict[str, str]:
    wf = build()
    bad = problems(wf)
    if bad:
        raise ValueError(f"Ask native workflow refused: {bad}")
    text = T._dump(wf)
    index = {
        "schema": "CioAskNativeWorkflowSet@v1",
        "generator": GENERATOR,
        "authority": "READ_ONLY_ADVISORY",
        "inert": "source candidate only; never imported or activated by this generator",
        "workflows": [
            {
                "id": WID,
                "kind": "native-business",
                "file": FILE,
                "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
                "graph_sha256": wf["meta"]["graph_sha256"],
                "policy_sha256": wf["meta"]["policy_sha256"],
                "node_types": sorted({n["type"] for n in wf["nodes"]}),
                "error_workflow": wf["settings"]["errorWorkflow"],
                "relay_calls": ["GET /due"],
                "health_contract": f"config/n8n_health_contracts.json#{HOURLY}",
                "runbook": "README.txt",
                "active": False,
            }
        ],
    }
    return {FILE: text, "INDEX.json": T._dump(index)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--check", action="store_true", help="fail if regeneration would change a byte")
    args = ap.parse_args(argv)
    out = Path(args.out)
    files = render()
    diffs = [
        name
        for name, text in sorted(files.items())
        if not (out / name).is_file() or (out / name).read_bytes() != text.encode("utf-8")
    ]
    if not args.check:
        out.mkdir(parents=True, exist_ok=True)
        for name in diffs:
            (out / name).write_text(files[name], encoding="utf-8")
    print(json.dumps({"mode": "check" if args.check else "write", "files": len(files), "diffs": diffs}))
    return int(args.check and bool(diffs))


if __name__ == "__main__":
    raise SystemExit(main())
