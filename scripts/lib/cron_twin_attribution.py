"""cron_twin_attribution.py — which registry lane a live crontab line belongs to, and nothing guessed.

Why (LQ-20261107-991, Fable audit item #1+#14): after the n8n cutover a lane can be *live on n8n*
(registry ``dispatch.mode == "live"``) while its old crontab line still fires. The two schedulers
share a flock, so the cron side wins and the n8n side records RUN_SKIPPED_LOCK — the lane looks
scheduled and is not running where it was declared. The audit counted 37 such lines by matching a
lane's script *basename* against the crontab. That count is wrong in both directions: a basename
also matches a sibling lane's line that passes different arguments (``data_gap_resolver.py
--pre-overnight`` is ``data-gap-resolver-pre``, not ``data-gap-resolver-at-0-10-16``), so eleven of
the audit's 37 were false positives. This module resolves a line to an owner by evidence, in order:

1. ``# TRADEAI_LANE <id>`` — the tag the cutover tool writes. Authoritative when the id is a row.
2. ``TRADEAI_EFFECT_CLAIM=<id>`` together with ``effect_claim_cron.sh <id>`` — the effect wrapper's
   own lane switch.
3. the row's ``scheduler.match`` text, normalised for the home prefix, occurring verbatim in the
   line. Compound lines can name several lanes; every one is an owner.
4. only when 1-3 find nobody: same script *and* same distinguishing arguments. A row matches when
   its script basename is on the line and its flag tokens and the line's flag tokens are equal as
   sets. Two siblings that differ only in ``--report-only`` / ``--dry-run`` / ``--apply`` therefore
   resolve to exactly one lane. More than one survivor is reported AMBIGUOUS and assigned to
   nobody: a line nobody can name is not a line to comment.

A retired row whose text drifted off its old line is *not* an owner of a sibling's line. That is
deliberate: commenting a sibling's live line would stop a running lane.

Snapshot text is sanitized before it is committed — ``/home/<user>`` becomes ``$HOME`` — because
the public repository carries no home path (scripts/check_no_pii.py, category ``home_path``). Both
sides of every comparison are normalised the same way, so the join is unaffected.

AUTHORITY: READ_ONLY_ADVISORY. Reads JSON config and crontab text; writes a file only when the
caller hands it a path (``write_snapshot`` / ``dump_baseline``). It never runs ``crontab`` itself
and never comments a line — ``scripts/n8n_cutover_wave.py comment-cron`` is the one host act.
"""
from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable, Mapping, Optional, Sequence

SNAPSHOT_SCHEMA = "CrontabSnapshot@v1"
BASELINE_SCHEMA = "CronTwinBaseline@v1"
CHECK_SCHEMA = "CronTwinCheck@v1"

#: First line of a committed snapshot. ``captured_at`` is what the staleness guard reads; the
#: checkout's file mtime is the clone time and cannot answer "how old is this crontab".
HEADER_RE = re.compile(r"^#\s*tradeai-crontab-snapshot\b.*captured_at=(\S+)")
HEADER_TEMPLATE = ("# tradeai-crontab-snapshot {schema} captured_at={ts} source={source} "
                   "sanitized_home=true — generated by scripts/check_cron_twins.py --write-snapshot")

TAG_RE = re.compile(r"#\s*TRADEAI_LANE\s+([A-Za-z0-9_.:-]+)")
EFFECT_ENV_RE = re.compile(r"TRADEAI_EFFECT_CLAIM=([A-Za-z0-9_.:-]+)")
ENV_LINE_RE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)=(.*)$")
SCRIPT_RE = re.compile(r"^[\w./+-]+\.(?:py|sh|js|mjs)$")

HOME_PREFIXES = ("/home/", "/Users/")


def is_live_line(line: str) -> bool:
    """A crontab line that fires: not blank, not a comment, not a variable assignment."""
    s = line.strip()
    return bool(s) and not s.startswith("#") and not ENV_LINE_RE.match(s)


def active_lines(text: str) -> list[tuple[int, str]]:
    """``[(1-based line number, line)]`` for every line that fires."""
    return [(i, ln) for i, ln in enumerate(text.splitlines(), start=1) if is_live_line(ln)]


def variable_definitions(text: str) -> dict[str, str]:
    """The crontab's own ``NAME=value`` lines (the only place ``$PY`` / ``$PROJ`` are defined)."""
    out: dict[str, str] = {}
    for ln in text.splitlines():
        if ln.lstrip().startswith("#"):
            continue
        m = ENV_LINE_RE.match(ln)
        if m:
            out[m.group(1)] = m.group(2).strip()
    return out


def normalize_text(text: str, home: Optional[str] = None) -> str:
    """The same line on every host: a home path becomes ``$HOME`` and ``~`` becomes ``$HOME``."""
    out = text
    homes = {h for h in (home, os.environ.get("HOME")) if h}
    for h in homes:
        if len(h.split("/")) >= 3:  # /home/<user> or /Users/<user>, never "/"
            out = out.replace(str(h), "$HOME")
    out = re.sub(r"(?<![\w$])~(?=/|\b)", "$HOME", out)
    for pre in HOME_PREFIXES:
        out = re.sub(re.escape(pre) + r"[^/\s\"';:]+", "$HOME", out)
    return out


def _unquote(token: str) -> str:
    return token.strip().strip("\"'`")


def script_tokens(text: str) -> set[str]:
    """Basenames of every script the text runs (quotes stripped; ``bash -c "… $PY x.py"`` included)."""
    out: set[str] = set()
    for raw in re.split(r"[\s;&|()<>]+", text):
        tok = _unquote(raw)
        if SCRIPT_RE.match(tok):
            out.add(tok.rsplit("/", 1)[-1])
    return out


def flag_tokens(text: str) -> set[str]:
    """The arguments that tell sibling lanes apart: ``--band premarket_scalp`` stays two tokens."""
    out: set[str] = set()
    for raw in re.split(r"[\s;&|()+]+", text):
        tok = _unquote(raw)
        if tok.startswith("--") and len(tok) > 2:
            out.add(tok)
    return out


def match_strings(row: Mapping[str, Any]) -> list[str]:
    sched = row.get("scheduler") or {}
    raw = sched.get("match") or ""
    vals = [raw] if isinstance(raw, str) else [str(x) for x in (raw or [])]
    return [v for v in vals if v.strip()]


def lane_ids(row: Mapping[str, Any]) -> list[str]:
    lid = str(row.get("lane_id") or "")
    return [lid] if lid else []


def _dispatch_mode(row: Mapping[str, Any]) -> Optional[str]:
    return (row.get("dispatch") or {}).get("mode")


def _row_state(row: Mapping[str, Any]) -> str:
    return str(row.get("state") or "")


def _scheduled_kind(row: Mapping[str, Any]) -> Optional[str]:
    return (row.get("scheduler") or {}).get("kind")


@dataclass
class Attribution:
    """What a live line is, and the evidence for saying so."""

    line_no: int
    line: str
    owners: dict[str, str] = field(default_factory=dict)   # lane_id -> method
    ambiguous: list[str] = field(default_factory=list)     # lane ids that tied on script+flags

    @property
    def owner_ids(self) -> list[str]:
        return sorted(self.owners)


def _tag_owner(line: str, rows: Mapping[str, Mapping[str, Any]]) -> Optional[str]:
    m = TAG_RE.search(line)
    if m and m.group(1) in rows:
        return m.group(1)
    return None


def _effect_owner(line: str, rows: Mapping[str, Mapping[str, Any]]) -> Optional[str]:
    m = EFFECT_ENV_RE.search(line)
    if not m or "effect_claim_cron.sh" not in line:
        return None
    lid = m.group(1)
    if lid in rows and re.search(r"effect_claim_cron\.sh\s+" + re.escape(lid) + r"\s", line):
        return lid
    return None


def attribute_line(line: str, rows: Mapping[str, Mapping[str, Any]], line_no: int = 0,
                   home: Optional[str] = None) -> Attribution:
    """Resolve one live crontab line to its lane(s). Never guesses between siblings."""
    a = Attribution(line_no=line_no, line=line)
    tagged = _tag_owner(line, rows) or _effect_owner(line, rows)
    if tagged:
        a.owners[tagged] = "tag" if _tag_owner(line, rows) else "effect_claim"
        return a

    norm_line = normalize_text(line, home)
    by_lane: dict[str, int] = {}
    for lid, row in rows.items():
        for m in match_strings(row):
            if normalize_text(m, home) in norm_line:
                by_lane[lid] = max(by_lane.get(lid, 0), len(m))
    if by_lane:
        for lid in by_lane:
            a.owners[lid] = "match"
        return a

    line_scripts = script_tokens(line)
    line_flags = flag_tokens(line)
    if not line_scripts:
        return a
    candidates: list[str] = []
    for lid, row in rows.items():
        for m in match_strings(row):
            if not (script_tokens(m) & line_scripts):
                continue
            if flag_tokens(m) == line_flags:
                candidates.append(lid)
                break
    if len(candidates) == 1:
        a.owners[candidates[0]] = "script+args"
    elif len(candidates) > 1:
        a.ambiguous = sorted(candidates)
    return a


def attribute_crontab(text: str, rows: Sequence[Mapping[str, Any]], *,
                      home: Optional[str] = None) -> list[Attribution]:
    by_id = {str(r.get("lane_id")): r for r in rows if r.get("lane_id")}
    return [attribute_line(ln, by_id, line_no=n, home=home) for n, ln in active_lines(text)]


# ── findings ──────────────────────────────────────────────────────────────────────────────────

TWIN = "N8N_LIVE_WITH_CRON_TWIN"
INACTIVE = "INACTIVE_LANE_BUT_CRON_LINE_ACTIVE"
AMBIGUOUS = "CRON_LINE_OWNER_AMBIGUOUS"


def findings(attributions: Iterable[Attribution], rows: Mapping[str, Mapping[str, Any]]) -> list[dict]:
    """Every line that fires for a lane the registry says n8n runs live, or has retired."""
    out: list[dict] = []
    for a in attributions:
        for lid in a.owner_ids:
            row = rows.get(lid) or {}
            base = {"lane_id": lid, "line_no": a.line_no, "line": a.line,
                    "method": a.owners[lid], "state": _row_state(row),
                    "dispatch_mode": _dispatch_mode(row), "scheduler_kind": _scheduled_kind(row)}
            if _row_state(row) == "ACTIVE" and _dispatch_mode(row) == "live":
                out.append({"code": TWIN, **base})
            elif _row_state(row) in ("RETIRED", "PAUSED", "NEVER_SCHEDULED"):
                out.append({"code": INACTIVE, **base})
        if a.ambiguous:
            out.append({"code": AMBIGUOUS, "lane_ids": a.ambiguous, "line_no": a.line_no,
                        "line": a.line, "method": "script+args tie"})
    return out


def finding_keys(items: Iterable[Mapping[str, Any]]) -> list[str]:
    """The baseline key: a lane id and the code. Line numbers and drifted text are not identity."""
    keys = []
    for f in items:
        if f["code"] == AMBIGUOUS:
            keys.append(AMBIGUOUS + ":" + ",".join(f["lane_ids"]))
        else:
            keys.append(f"{f['code']}:{f['lane_id']}")
    return keys


# ── snapshot text ────────────────────────────────────────────────────────────────────────────

def capture_time(text: str) -> Optional[datetime]:
    """The ``captured_at`` in a snapshot's header, or None (an unstamped file is not a snapshot)."""
    for ln in text.splitlines()[:5]:
        m = HEADER_RE.match(ln.strip())
        if m:
            raw = m.group(1).strip()
            if raw.endswith("Z"):
                raw = raw[:-1] + "+00:00"
            try:
                dt = datetime.fromisoformat(raw)
            except ValueError:
                return None
            return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)
    return None


def snapshot_age_days(text: str, *, now: Optional[datetime] = None) -> Optional[float]:
    ts = capture_time(text)
    if ts is None:
        return None
    now = now or datetime.now(timezone.utc)
    return (now - ts).total_seconds() / 86400.0


def render_snapshot(text: str, *, source: str, now: Optional[datetime] = None,
                    home: Optional[str] = None) -> str:
    """The committed, sanitized form of a crontab: header, then every line, home path removed."""
    now = now or datetime.now(timezone.utc)
    stamp = now.replace(microsecond=0).isoformat()
    header = HEADER_TEMPLATE.format(schema=SNAPSHOT_SCHEMA, ts=stamp, source=source)
    body = [normalize_text(ln, home).rstrip() for ln in text.splitlines()]
    while body and not body[0].strip():
        body.pop(0)
    return "\n".join([header, *body]) + "\n"


# ── dev-tree interpreter (#14) ───────────────────────────────────────────────────────────────

RELEASE_MARKER = "/portfolio-server/CURRENT"


def dev_tree_lines(text: str) -> dict[str, Any]:
    """Active lines that run the dev-tree ``$PY`` instead of the served release's interpreter.

    The crontab defines one ``PY=``. If that definition does not point at the served release
    (``portfolio-server/CURRENT``), every line that uses ``$PY`` runs code from the rebuild tree.
    One variable edit re-points all of them, which is why the count matters more than the list.
    """
    defs = variable_definitions(text)
    py = defs.get("PY", "")
    out = {"py_definition": py, "uses_release": RELEASE_MARKER in py, "count": 0, "line_nos": []}
    if not py or out["uses_release"]:
        return out
    for n, ln in active_lines(text):
        if "$PY" in ln or ("${PY}" in ln):
            out["line_nos"].append(n)
    out["count"] = len(out["line_nos"])
    return out


# ── baseline ─────────────────────────────────────────────────────────────────────────────────

def load_baseline(path: Path) -> Optional[dict]:
    if not path.is_file():
        return None
    doc = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(doc, dict) or doc.get("schema") != BASELINE_SCHEMA:
        raise ValueError(f"{path}: schema must be {BASELINE_SCHEMA!r}")
    return doc


def dump_baseline(items: Iterable[Mapping[str, Any]], *, now: Optional[datetime] = None,
                  note: str = "") -> dict:
    """A shrink-only baseline of inherited findings, in a stable order."""
    now = now or datetime.now(timezone.utc)
    lanes = []
    for f in sorted(items, key=lambda x: (x["code"], x.get("lane_id") or ",".join(x.get("lane_ids") or []))):
        if f["code"] == AMBIGUOUS:
            key = AMBIGUOUS + ":" + ",".join(f["lane_ids"])
            entry = {"key": key, "code": AMBIGUOUS, "lane_ids": list(f["lane_ids"])}
        else:
            key = f"{f['code']}:{f['lane_id']}"
            entry = {"key": key, "code": f["code"], "lane_id": f["lane_id"]}
        entry.update({"line_no": f["line_no"], "evidence": str(f["line"]).strip()[:240]})
        lanes.append(entry)
    return {"schema": BASELINE_SCHEMA, "as_of": now.replace(microsecond=0).isoformat(),
            "note": note, "findings": lanes}


