"""Historical base rates for the Market Risk deep brief — "what normally happens when X is happening".

Operator 2026-10-31: "as part of the deeper analysis after the initial alert ... the historical facts on what normally
happens in the market when X is happening." Design DSN-20261031-market-risk-engine (deep brief follow-up).

Deterministic, never fitted, never scored:

* ``features_at`` turns daily closes into the conditions the brief matches on: the breadth PATTERN of the week
  (BROAD = most sectors down together; CONCENTRATED_TECH = tech/semis down while defensives hold; MIXED), the VIX
  level bucket and its 5-session direction, the semiconductor (SOXX) drawdown bucket and sector breadth (share of the
  sector SPDRs above their 50-day average). Every one is computable on the day from closes up to that day.
* The table ``base_rates_table.json.gz`` is GENERATED by ``scripts/market_risk_base_rates_build.py`` from the public
  10-year daily fixture (tests/fixtures/market_risk_scenarios). 2026 is held out: no row is dated 2026 and no forward
  outcome reaches into 2026. Never hand-edit it; regenerate it.
* ``conditional`` matches today's conditions against history, dropping the least important condition until at least
  ``min_n`` days match, and reports every statistic with its sample size. Below ``min_n`` it says
  "insufficient history" rather than inventing a figure.
* ``analogs`` lists the nearest past dates by feature distance. EXPLANATION ONLY: nothing in the engine's score or tier
  reads this module (a test enforces it).

No position data, no sizes, no orders (MBI_BEHAVIOR = 0). Public market data only.
"""

from __future__ import annotations

import gzip
import json
import math
from datetime import date
from functools import lru_cache
from pathlib import Path
from statistics import median
from typing import Any, Iterable, Optional

TABLE_PATH = Path(__file__).resolve().parent / "base_rates_table.json.gz"
TABLE_SCHEMA = "MarketRiskBaseRates@v1"

SECTOR_ETFS = ("XLK", "XLC", "XLY", "XLP", "XLV", "XLU", "XLE", "XLF", "XLI", "XLB", "XLRE")
GROUPS = SECTOR_ETFS + ("SMH",)
DEFENSIVES = ("XLP", "XLV", "XLU")
TECH = ("XLK", "SMH")
INDEXES = ("SPY", "QQQ")
HORIZONS = (1, 5, 20, 60)
GROUP_HORIZONS = (5, 20)
CONDITION_ORDER = ("pattern", "vix_b", "sox_b", "breadth_b", "vix_dir")  # dropped from the right when n is short
NUMERIC = ("spy_dd20", "sox_dd52", "vix", "breadth50", "tech_rel5", "def5")


def _ret(series: list[float], k: int) -> Optional[float]:
    if len(series) <= k or not series[-1 - k]:
        return None
    return series[-1] / series[-1 - k] - 1.0


def _bucket(v: Optional[float], edges: Iterable[float], labels: Iterable[str]) -> Optional[str]:
    if v is None:
        return None
    labels = list(labels)
    for e, lab in zip(edges, labels):
        if v < e:
            return lab
    return labels[-1]


def features_at(closes: dict[str, list[float]], *, thresholds: Optional[dict[str, float]] = None) -> dict[str, Any]:
    """Conditions from each symbol's closes UP TO AND INCLUDING the evaluation day (oldest first). Missing inputs give
    ``None`` features, never zero."""
    t = {"broad_n_down": 8, "broad_drop": -0.02, "tech_rel": -0.03, "def_floor": -0.005, **(thresholds or {})}
    out: dict[str, Any] = {}
    spy = closes.get("SPY") or []
    out["spy_dd20"] = (spy[-1] / max(spy[-20:]) - 1.0) if len(spy) >= 20 else None
    sox = closes.get("SOXX") or closes.get("SMH") or []
    out["sox_dd52"] = (sox[-1] / max(sox[-252:]) - 1.0) if len(sox) >= 60 else None
    vix = closes.get("^VIX") or []
    out["vix"] = vix[-1] if vix else None
    out["vix_chg5"] = _ret(vix, 5)
    above, have = 0, 0
    r5: dict[str, float] = {}
    for s in SECTOR_ETFS:
        c = closes.get(s) or []
        if len(c) >= 50:
            have += 1
            above += int(c[-1] > sum(c[-50:]) / 50.0)
        r = _ret(c, 5)
        if r is not None:
            r5[s] = r
    out["breadth50"] = (above / have) if have >= 6 else None
    smh5 = _ret(closes.get("SMH") or [], 5)
    tech = [x for x in (r5.get("XLK"), smh5) if x is not None]
    out["tech_rel5"] = (sum(tech) / len(tech) - median(r5.values())) if tech and len(r5) >= 6 else None
    d = [r5[s] for s in DEFENSIVES if s in r5]
    out["def5"] = (sum(d) / len(d)) if d else None
    out["n_down5"] = sum(1 for v in r5.values() if v <= t["broad_drop"]) if len(r5) >= 6 else None
    worst = sorted(((v, s) for s, v in {**r5, **({"SMH": smh5} if smh5 is not None else {})}.items()))
    out["worst5"] = worst[0][1] if worst else None
    if out["n_down5"] is None or out["tech_rel5"] is None or out["def5"] is None:
        out["pattern"] = None
    elif out["n_down5"] >= t["broad_n_down"]:
        out["pattern"] = "BROAD"
    elif out["tech_rel5"] <= t["tech_rel"] and out["def5"] >= t["def_floor"]:
        out["pattern"] = "CONCENTRATED_TECH"
    else:
        out["pattern"] = "MIXED"
    sdd = out["sox_dd52"]
    out["sox_b"] = _bucket(None if sdd is None else -sdd, (0.10, 0.20, 0.30), ("<10%", "10-20%", "20-30%", "30%+"))
    out["vix_b"] = _bucket(out["vix"], (15, 20, 25, 30), ("<15", "15-20", "20-25", "25-30", "30+"))
    vc = out["vix_chg5"]
    out["vix_dir"] = None if vc is None else ("up" if vc >= 0.05 else "down" if vc <= -0.05 else "flat")
    out["breadth_b"] = _bucket(out["breadth50"], (0.30, 0.70), ("low", "mid", "high"))
    return out


# ── the generated table ────────────────────────────────────────────────────────────────────────────────────────
@lru_cache(maxsize=2)
def load_table(path: str = str(TABLE_PATH)) -> dict[str, Any]:
    with gzip.open(path, "rt", encoding="utf-8") as fh:
        data = json.load(fh)
    if data.get("schema") != TABLE_SCHEMA:
        raise ValueError(f"{path}: expected {TABLE_SCHEMA}, got {data.get('schema')!r}")
    return data


def _matches(row: dict[str, Any], feats: dict[str, Any], conds: tuple[str, ...]) -> bool:
    f = row["f"]
    return all(feats.get(c) is not None and f.get(c) == feats.get(c) for c in conds)


def _dist(values: list[float]) -> dict[str, Any]:
    v = sorted(values)
    n = len(v)
    if not n:
        return {"n": 0}

    def q(p: float) -> float:
        return v[min(n - 1, max(0, int(round(p * (n - 1)))))]

    return {
        "n": n,
        "median_pct": round(100 * median(v), 2),
        "p10_pct": round(100 * q(0.10), 2),
        "p90_pct": round(100 * q(0.90), 2),
        "share_negative_pct": round(100 * sum(1 for x in v if x < 0) / n, 1),
    }


def conditional(
    feats: dict[str, Any],
    *,
    min_n: int = 20,
    group: Optional[str] = None,
    table: Optional[dict[str, Any]] = None,
) -> dict[str, Any]:
    """Forward-return distributions given today's conditions, with backoff and sample sizes on everything."""
    table = table or load_table()
    rows = table["rows"]
    conds = tuple(c for c in CONDITION_ORDER if feats.get(c) is not None)
    used: tuple[str, ...] = ()
    matched: list[dict[str, Any]] = []
    for k in range(len(conds), 0, -1):
        cand = [r for r in rows if _matches(r, feats, conds[:k])]
        if len(cand) >= min_n:
            used, matched = conds[:k], cand
            break
    out: dict[str, Any] = {
        "schema": "MarketRiskConditional@v1",
        "table_as_of": table.get("generated_from"),
        "holdout": table.get("holdout"),
        "conditions": {c: feats.get(c) for c in used},
        "dropped": [c for c in conds if c not in used],
        "n_days": len(matched),
        "min_n": min_n,
    }
    if not matched:
        out["insufficient_history"] = True
        return out
    for sym in INDEXES:
        out[sym] = {
            f"{h}d": _dist([r["o"][sym][str(h)] for r in matched if r["o"].get(sym, {}).get(str(h)) is not None])
            for h in HORIZONS
        }
    if group and group in GROUPS:
        out["group"] = group
        out[group] = {
            f"{h}d": _dist([r["o"][group][str(h)] for r in matched if r["o"].get(group, {}).get(str(h)) is not None])
            for h in GROUP_HORIZONS
        }
    drop = [r["o"]["SPY"]["drop5_20"] for r in matched if r["o"]["SPY"].get("drop5_20") is not None]
    trough = [r["o"]["SPY"]["trough60"] for r in matched if r["o"]["SPY"].get("trough60") is not None]
    rec = [r["o"]["SPY"].get("recover120") for r in matched if "recover120" in r["o"]["SPY"]]
    recovered = [x for x in rec if x is not None]
    out["spy_further_5pct_drop_within_20d"] = {
        "n": len(drop),
        "hit_rate_pct": round(100 * sum(drop) / len(drop), 1) if drop else None,
    }
    out["spy_sessions_to_trough_within_60d"] = {"n": len(trough), "median": median(trough) if trough else None}
    out["spy_sessions_to_recover"] = {
        "n": len(rec),
        "recovered_within_120d": len(recovered),
        "median": median(recovered) if recovered else None,
    }
    for block in [out.get(s) for s in (*INDEXES, group)] + [out["spy_further_5pct_drop_within_20d"]]:
        if isinstance(block, dict):
            for v in block.values() if all(isinstance(x, dict) for x in block.values()) else [block]:
                if isinstance(v, dict) and 0 < int(v.get("n") or 0) < min_n:
                    v["insufficient_history"] = True
    return out


def analogs(feats: dict[str, Any], *, k: int = 3, min_gap_days: int = 30, table: Optional[dict] = None) -> list[dict]:
    """Nearest past dates by standardized feature distance — for EXPLANATION only, never scored."""
    table = table or load_table()
    rows = [r for r in table["rows"] if all(r["f"].get(x) is not None for x in NUMERIC)]
    if not rows or any(feats.get(x) is None for x in NUMERIC):
        return []
    stats = {}
    for x in NUMERIC:
        vals = [r["f"][x] for r in rows]
        mu = sum(vals) / len(vals)
        sd = math.sqrt(sum((v - mu) ** 2 for v in vals) / len(vals)) or 1.0
        stats[x] = (mu, sd)

    def dist(f: dict) -> float:
        return math.sqrt(sum(((f[x] - feats[x]) / stats[x][1]) ** 2 for x in NUMERIC))

    ranked = sorted(rows, key=lambda r: dist(r["f"]))
    picked: list[dict] = []
    for r in ranked:
        d = date.fromisoformat(r["d"])
        if all(abs((d - date.fromisoformat(p["date"])).days) >= min_gap_days for p in picked):
            picked.append(
                {
                    "date": r["d"],
                    "distance": round(dist(r["f"]), 2),
                    "pattern": r["f"].get("pattern"),
                    "spy_next_20d_pct": None
                    if r["o"]["SPY"].get("20") is None
                    else round(100 * r["o"]["SPY"]["20"], 2),
                }
            )
        if len(picked) >= k:
            break
    return picked
