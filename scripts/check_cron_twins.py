#!/usr/bin/env python3
"""check_cron_twins.py — an n8n-live lane must not still own a firing crontab line.

Why (LQ-20261107-991, Fable n8n design audit Q6 #1+#14): the cutover keeps the cron line
during parity on purpose, and retires it as a host act. If the line is never retired, the lane
has two schedulers: the crontab fires, the n8n workflow fires, they collide on the lane's flock,
and the n8n run records RUN_SKIPPED_LOCK. The lane is declared live on n8n and is in fact
running on cron — a green health page over a cutover that did not happen. Nothing in CI noticed,
because nothing compared the registry's ``dispatch.mode`` to the crontab at all.

This gate compares them, every build, against a snapshot of the crontab that is committed to the
repository:

* On the host, it reads the live crontab (``crontab -l``, else cron's fresh snapshot).
  Read-only: it never runs ``crontab`` with an editing flag and never comments a line.
* In CI there is no user crontab, so it reads ``config/crontab_snapshot.txt`` — regenerated by
  ``--write-snapshot``, sanitized (``/home/<user>`` → ``$HOME``) so the public repository
  carries no home path. An unstamped or stale snapshot is CANNOT RUN (exit 2), never clean:
  a gate that passes because it had no input is the defect this repository keeps re-learning.

Attribution is by evidence, not by script basename: see ``scripts/lib/cron_twin_attribution.py``.
Eleven of the audit's 37 "twins" were a sibling lane's line that runs the same script with
different arguments; commenting those would stop a lane that is running correctly.

Findings, and what each one means for the operator:

  N8N_LIVE_WITH_CRON_TWIN       a lane with dispatch.mode=live still owns a firing cron line.
                                The operator retires the line with
                                ``n8n_cutover_wave.py comment-cron --lanes <ids> --apply``.
  INACTIVE_LANE_BUT_CRON_LINE_ACTIVE
                                a RETIRED/PAUSED lane still owns a firing line. The lane runs
                                and the registry says it does not.
  CRON_LINE_OWNER_AMBIGUOUS     two rows match a line on script+arguments. Nobody is assigned,
                                nobody is commented: a line nobody can name is not a line to
                                touch. Add a ``# TRADEAI_LANE <id>`` tag or fix the match.

Exit codes (distinct because 2-for-missing-file has read as a pass here before):

    0  clean, or only findings already in the shrink-only inherited baseline
    1  a finding not in the baseline (``--fail-on-new``)
    2  the gate could not run: registry or snapshot unreadable, unstamped, stale

Usage:
    python3 scripts/check_cron_twins.py                       # report against the live/host crontab
    python3 scripts/check_cron_twins.py --fail-on-new --json  # CI mode
    python3 scripts/check_cron_twins.py --snapshot FILE        # grade a specific crontab text
    python3 scripts/check_cron_twins.py --from FILE --write-snapshot config/crontab_snapshot.txt
    python3 scripts/check_cron_twins.py --emit-baseline config/cron_twin_baseline.json
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from lib import cron_twin_attribution as CTA  # noqa: E402

EXIT_OK = 0
EXIT_VIOLATION = 1
EXIT_CANNOT_RUN = 2

DEFAULT_REGISTRY = ROOT / "config" / "lane_registry.json"
DEFAULT_SNAPSHOT = ROOT / "config" / "crontab_snapshot.txt"
DEFAULT_BASELINE = ROOT / "config" / "cron_twin_baseline.json"


def _fail(msg: str) -> int:
    print(f"cron twin guard: CANNOT RUN — {msg}", file=sys.stderr)
    return EXIT_CANNOT_RUN


def load_rows(path: Path) -> dict[str, dict]:
    if not path.is_file():
        raise FileNotFoundError(f"registry not found: {path}")
    doc = json.loads(path.read_text(encoding="utf-8"))
    lanes = doc.get("lanes") if isinstance(doc, dict) else None
    if not isinstance(lanes, list):
        raise ValueError(f"{path}: no 'lanes' list")
    rows: dict[str, dict] = {}
    for row in lanes:
        if not isinstance(row, dict) or not row.get("lane_id"):
            raise ValueError(f"{path}: a lane row has no lane_id")
        rid = str(row["lane_id"])
        if rid in rows:
            raise ValueError(f"{path}: duplicate lane_id {rid!r}")
        rows[rid] = row
    return rows


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def resolve_source(args) -> tuple[str, str, str]:
    """``(text, source_label, captured_at_iso)`` or raise ValueError with the reason it cannot run."""
    if args.snapshot:
        p = Path(args.snapshot)
        if not p.is_file():
            raise ValueError(f"--snapshot not found: {p}")
        return read_text(p), f"file:{p}", ""

    if args.source != "committed":
        from lib.crontab_snapshot import read_crontab  # local: CI never needs the import
        got = read_crontab()
        if got.ok and len(CTA.active_lines(got.text)) > 0:
            age = f" age={got.age_s/60:.0f}m" if got.age_s is not None else ""
            return got.text, f"live:{got.source}{age}", ""

    p = Path(args.committed_snapshot)
    if not p.is_file():
        raise ValueError(
            f"no live crontab and no committed snapshot at {p}; the gate has no input. "
            f"Regenerate it with: python3 scripts/check_cron_twins.py --write-snapshot {p}")
    text = read_text(p)
    age = CTA.snapshot_age_days(text)
    if age is None:
        raise ValueError(f"{p} has no 'captured_at' header; an unstamped file cannot be aged "
                         f"and is not a snapshot (regenerate with --write-snapshot)")
    if args.max_age_days and age > args.max_age_days:
        raise ValueError(
            f"{p} was captured {age:.1f} days ago (> {args.max_age_days}d). A stale snapshot grades "
            f"a crontab that is not today's. Regenerate with: "
            f"python3 scripts/check_cron_twins.py --write-snapshot {p}")
    return text, f"committed:{p}", CTA.capture_time(text).isoformat()


def report_text(doc: dict) -> None:
    src = doc["source"]
    print(f"cron twin guard: source={src['label']}"
          + (f" captured={src['captured_at']}" if src.get("captured_at") else "")
          + (f" age={src['age_days']:.1f}d" if src.get("age_days") is not None else ""))
    c = doc["counts"]
    print(f"  registry rows        : {c['rows']}")
    print(f"  active crontab lines : {c['active_lines']}")
    print(f"  n8n-live twin lines  : {c['twin_lines']} across {c['twin_lanes']} lanes")
    print(f"  inactive-owner lines : {c['inactive_lines']}")
    print(f"  ambiguous lines      : {c['ambiguous_lines']}")
    print(f"  inherited baseline   : {c['baseline_entries']}")
    print(f"  NEW (fail on --fail-on-new): {len(doc['new'])}")
    dt = doc["dev_tree"]
    if dt["count"] or dt["py_definition"]:
        rel = "release" if dt["uses_release"] else "DEV TREE"
        print(f"  $PY interpreter      : {rel}  ({dt['py_definition'] or 'undefined'})")
        print(f"  lines using $PY      : {dt['count']}")
    for f in doc["findings"]:
        lane = f.get("lane_id") or ",".join(f.get("lane_ids") or [])
        mark = "NEW " if f["key"] in doc["new_keys"] else "    "
        print(f"  {mark}{f['code']:<34} {lane:<46} L{f['line_no']:<5} [{f['method']}]")
    stale = doc.get("baseline_stale") or []
    if stale:
        print(f"  baseline entries no longer found: {len(stale)} (prune with --prune-baseline)")
        for s in stale:
            print(f"    - {s}")
    if not doc["findings"]:
        print("cron twins: clean — no n8n-live or retired lane owns a firing crontab line")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--registry", default=str(DEFAULT_REGISTRY))
    ap.add_argument("--snapshot", default=None,
                    help="grade this crontab text instead of reading the host (tests, evidence)")
    ap.add_argument("--committed-snapshot", default=str(DEFAULT_SNAPSHOT),
                    help="the snapshot CI reads when there is no live crontab")
    ap.add_argument("--source", choices=("auto", "live", "committed"), default="auto",
                    help="auto (default): live crontab when readable, else the committed snapshot")
    ap.add_argument("--max-age-days", type=float, default=30.0,
                    help="a committed snapshot older than this is CANNOT RUN (0 disables)")
    ap.add_argument("--baseline", default=str(DEFAULT_BASELINE))
    ap.add_argument("--fail-on-new", action="store_true",
                    help="exit 1 when a finding is not in the inherited baseline")
    ap.add_argument("--no-baseline", action="store_true",
                    help="ignore the baseline entirely: every finding is new")
    ap.add_argument("--json", action="store_true", help="print the full check document")
    ap.add_argument("--list-dev-tree", action="store_true",
                    help="print every active line that runs the dev-tree $PY")
    ap.add_argument("--from", dest="from_file", default=None,
                    help="with --write-snapshot: sanitize this crontab text instead of the host")
    ap.add_argument("--source-label", default=None,
                    help="with --write-snapshot: what the snapshot's header records as its origin")
    ap.add_argument("--write-snapshot", default=None, metavar="PATH",
                    help="write a sanitized, stamped snapshot (the operator's host act for CI)")
    ap.add_argument("--emit-baseline", default=None, metavar="PATH",
                    help="write the current findings as the inherited baseline")
    ap.add_argument("--prune-baseline", action="store_true",
                    help="with --emit-baseline: keep only findings that still reproduce")
    args = ap.parse_args(argv)

    # ── snapshot writer (no registry needed) ────────────────────────────────────────────────
    if args.write_snapshot:
        if args.from_file:
            p = Path(args.from_file)
            if not p.is_file():
                return _fail(f"--from not found: {p}")
            text, label = read_text(p), f"file:{p.name}"
        else:
            from lib.crontab_snapshot import read_crontab
            got = read_crontab()
            if not got.ok:
                return _fail(f"no crontab to snapshot: {got.error}")
            text, label = got.text, f"crontab({got.source})"
        if args.source_label:
            label = args.source_label
        out = Path(args.write_snapshot)
        out.parent.mkdir(parents=True, exist_ok=True)
        stamp = datetime.now(timezone.utc)
        out.write_text(CTA.render_snapshot(text, source=label, now=stamp), encoding="utf-8")
        print(f"wrote {out}  captured_at={stamp.replace(microsecond=0).isoformat()}  "
              f"active_lines={len(CTA.active_lines(text))}  source={label}")
        return EXIT_OK

    # ── load inputs ─────────────────────────────────────────────────────────────────────────
    try:
        rows = load_rows(Path(args.registry))
    except (OSError, ValueError) as exc:
        return _fail(str(exc))
    try:
        text, label, captured = resolve_source(args)
    except ValueError as exc:
        return _fail(str(exc))

    attributions = CTA.attribute_crontab(text, list(rows.values()))
    items = CTA.findings(attributions, rows)
    for f in items:
        f["key"] = CTA.finding_keys([f])[0]

    baseline_entries: list[str] = []
    baseline_stale: list[str] = []
    if not args.no_baseline:
        try:
            base = CTA.load_baseline(Path(args.baseline))
        except (OSError, ValueError) as exc:
            return _fail(str(exc))
        if base:
            baseline_entries = [str(e.get("key")) for e in base.get("findings") or [] if e.get("key")]
            present = {f["key"] for f in items}
            baseline_stale = [k for k in baseline_entries if k not in present]

    base_set = set(baseline_entries)
    new = [f for f in items if f["key"] not in base_set]
    dev = CTA.dev_tree_lines(text)

    age = CTA.snapshot_age_days(text)
    by_lane: dict[str, int] = {}
    for f in items:
        if f["code"] == CTA.TWIN:
            by_lane[f["lane_id"]] = by_lane.get(f["lane_id"], 0) + 1
    doc = {
        "schema": CTA.CHECK_SCHEMA,
        "source": {"label": label, "captured_at": captured or None, "age_days": age},
        "counts": {
            "rows": len(rows), "active_lines": len(CTA.active_lines(text)),
            "twin_lines": sum(by_lane.values()), "twin_lanes": len(by_lane),
            "inactive_lines": sum(1 for f in items if f["code"] == CTA.INACTIVE),
            "ambiguous_lines": sum(1 for f in items if f["code"] == CTA.AMBIGUOUS),
            "baseline_entries": len(baseline_entries),
        },
        "findings": items,
        "new": new,
        "new_keys": [f["key"] for f in new],
        "baseline_stale": baseline_stale,
        "dev_tree": dev,
    }

    if args.emit_baseline:
        out = Path(args.emit_baseline)
        dump = CTA.dump_baseline(items, note="inherited debt from the n8n cutover; shrinks as the "
                                             "operator retires cron lines (LQ-20261107-991)")
        if args.prune_baseline:
            dump["findings"] = [e for e in dump["findings"] if e["key"] in {f["key"] for f in items}]
        out.write_text(json.dumps(dump, indent=1) + "\n", encoding="utf-8")
        print(f"wrote {out}  findings={len(dump['findings'])}")
        return EXIT_OK

    if args.json:
        print(json.dumps(doc, indent=1))
    else:
        report_text(doc)
        if args.list_dev_tree:
            print("\nactive lines using the dev-tree $PY:")
            lines = CTA.active_lines(text)
            for n in dev["line_nos"]:
                print(f"  L{n}: {CTA.normalize_text(lines[n - 1][1])[:160]}")

    if args.fail_on_new and new:
        print(f"\n{len(new)} n8n-live lane(s) still own a firing crontab line. Parity is over: retire the\n"
              "line at the host (scripts/n8n_cutover_wave.py comment-cron --lanes <ids> --dry-run first),\n"
              "then regenerate the snapshot and prune the baseline. A lane on two schedulers records\n"
              "RUN_SKIPPED_LOCK on the n8n side and looks healthy while running on cron.",
              file=sys.stderr)
        for f in new:
            print(f"  {f['code']} {f.get('lane_id') or f.get('lane_ids')} L{f['line_no']}", file=sys.stderr)
        return EXIT_VIOLATION
    return EXIT_OK


if __name__ == "__main__":
    raise SystemExit(main())
